import java.awt.*;
import java.awt.image.BufferedImage;
import java.io.*;

// Build-time tool: pre-renders printable ASCII of two TTFs (regular, bold) into a Java class of
// glyph alpha masks, so Forms can draw text without starting the font system at runtime.
// usage: GlyphGen <out.java> <regular.ttf> <bold.ttf> [className] [pixelSize]
// Each glyph is (advance + 2 * PAD) x HEIGHT pixels, glyphs one after another; each pixel is one
// char 'a'..'p' (alpha / 17). Advances are one char each, 'a' + advance.
public class GlyphGen {
    static final int FIRST = 32, LAST = 126;

    public static void main(String[] a) throws Exception {
        String cls = a.length > 3 ? a[3] : "Glyphs";
        float size = a.length > 4 ? Float.parseFloat(a[4]) : 12f;
        Font reg = Font.createFont(Font.TRUETYPE_FONT, new File(a[1])).deriveFont(size);
        Font bold = Font.createFont(Font.TRUETYPE_FONT, new File(a[2])).deriveFont(size);
        BufferedImage probe = new BufferedImage(1, 1, BufferedImage.TYPE_INT_ARGB);
        FontMetrics fm = probe.createGraphics().getFontMetrics(reg);
        int pad = Math.max(1, Math.round(size / 12)), ascent = fm.getAscent() + pad - 1, height = fm.getAscent() + fm.getDescent() + pad;
        if (size == 12f) { ascent = 11; height = 14; } // the original table's metrics
        StringBuilder out = new StringBuilder();
        out.append("// Generated by tools/GlyphGen.java from Liberation Sans ").append((int) size).append("px. Do not edit.\n");
        out.append("final class ").append(cls).append(" {\n");
        out.append("    static final int FIRST = ").append(FIRST).append(", LAST = ").append(LAST)
            .append(", ASCENT = ").append(ascent).append(", HEIGHT = ").append(height).append(", PAD = ").append(pad).append(";\n");
        emit(out, "REGULAR", reg, ascent, height, pad);
        emit(out, "BOLD", bold, ascent, height, pad);
        out.append("}\n");
        Writer w = new OutputStreamWriter(new FileOutputStream(a[0]), "UTF-8");
        w.write(out.toString());
        w.close();
    }

    static void emit(StringBuilder out, String name, Font font, int ascent, int height, int pad) {
        StringBuilder adv = new StringBuilder(), px = new StringBuilder();
        for (char ch = FIRST; ch <= LAST; ch++) {
            BufferedImage probe = new BufferedImage(1, 1, BufferedImage.TYPE_INT_ARGB);
            int w = probe.createGraphics().getFontMetrics(font).charWidth(ch);
            adv.append((char) ('a' + w));
            int cw = w + 2 * pad;
            BufferedImage img = new BufferedImage(cw, height, BufferedImage.TYPE_INT_ARGB);
            Graphics2D g = img.createGraphics();
            g.setRenderingHint(RenderingHints.KEY_TEXT_ANTIALIASING, RenderingHints.VALUE_TEXT_ANTIALIAS_ON);
            g.setFont(font);
            g.setColor(Color.BLACK);
            g.drawString(String.valueOf(ch), pad, ascent);
            g.dispose();
            for (int y = 0; y < height; y++)
                for (int x = 0; x < cw; x++) px.append((char) ('a' + Math.round((img.getRGB(x, y) >>> 24) / 17f)));
        }
        // .toString() keeps these from being compile-time constants: javac would otherwise copy
        // the strings into every class that reads them, and the jar would carry them twice.
        out.append("    static final String ").append(name).append("_ADV = \"").append(adv).append("\".toString();\n");
        out.append("    static final String ").append(name).append(" = \"").append(px).append("\".toString();\n");
    }
}
